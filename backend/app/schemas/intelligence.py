class IntelligenceQueryRequest(BaseModel):
    batch_identifier: Optional[str] = Field(None, description="Batch UUID or business batch number")
    target_batch_id: Optional[str] = Field(None, description="Alias for batch_identifier")
    question: Optional[str] = Field(None, min_length=3, max_length=1500, description="Question regarding batch quality, defects, inspections, or release")
    prompt: Optional[str] = Field(None, min_length=3, max_length=1500, description="Alias for question")

    @model_validator(mode="after")
    def resolve_aliases(self) -> "IntelligenceQueryRequest":
        b_id = self.batch_identifier or self.target_batch_id
        if not b_id or not b_id.strip():
            raise ValueError("A batch identifier ('batch_identifier' or 'target_batch_id') must be provided.")
        self.batch_identifier = b_id.strip()

        q = self.question or self.prompt
        if not q or not q.strip():
            raise ValueError("A question ('question' or 'prompt') must be provided.")
        self.question = q.strip()
        return self


class IntelligenceQueryResponse(BaseModel):
    answer: str = Field(..., description="Evidence-grounded natural language explanation")
    is_fallback: bool = Field(False, description="True if response is deterministic fallback without live model inference")
    model_provider: str = Field("gemini", description="AI service provider")
    model_name: str = Field("gemini-flash-lite-latest", description="Model architecture/name used")
    deterministic_metrics: DeterministicQualityMetrics = Field(..., description="Computed SQL/Python ground truth metrics")
    retrieved_source_ids: List[SourceReference] = Field(..., description="Stable source record IDs retrieved from database")
    citations: List[Citation] = Field(default_factory=list, description="Verified citations matched in the generated answer")
    unverified_citations: List[str] = Field(default_factory=list, description="Citations generated by model that could not be verified")
    limitations: List[str] = Field(..., description="Explicit disclaimers and scope limitations")
    disclaimer: str = Field(
        "AI response grounded strictly in database records. GenAI has no authority to alter quality or release status.",
        description="Standard compliance disclaimer",
    )
    latency_ms: Optional[int] = Field(None, description="Total retrieval and processing latency in milliseconds")


