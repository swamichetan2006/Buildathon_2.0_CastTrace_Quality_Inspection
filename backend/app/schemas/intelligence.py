class AttentionPriority(str, Enum):
    CRITICAL = "CRITICAL"
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"


class AttentionCategory(str, Enum):
    RELEASE_BLOCKER = "RELEASE_BLOCKER"
    DEFECT = "DEFECT"
    CORRECTIVE_ACTION = "CORRECTIVE_ACTION"
    INSPECTION = "INSPECTION"
    REVIEW = "REVIEW"


class AttentionItem(BaseModel):
    item_id: str = Field(..., description="Stable deterministic item ID, e.g. ATTN-defects-<uuid>")
    priority: AttentionPriority = Field(..., description="Action priority: CRITICAL, HIGH, MEDIUM, LOW")
    category: AttentionCategory = Field(..., description="Domain category")
    reason_code: str = Field(..., description="Machine-readable reason code")
    title: str = Field(..., description="Short summary title")
    explanation: str = Field(..., description="Human-readable explanation based on actual record values")
    batch_id: Optional[str] = Field(None, description="Related Batch UUID")
    batch_number: Optional[str] = Field(None, description="Related business batch number")
    entity_type: str = Field(..., description="Entity table name (batches, inspections, defects, corrective_actions, inspection_items)")
    entity_id: str = Field(..., description="Target entity primary key UUID")
    business_identifier: str = Field(..., description="Human-readable business identifier (DEF-..., CAPA-..., INSP-..., BATCH-...)")
    current_status: str = Field(..., description="Current status of the underlying record")
    due_date: Optional[date] = Field(None, description="Due date for corrective actions if applicable")
    is_overdue: bool = Field(False, description="Whether record is past due date as of current date")
    related_defect_id: Optional[str] = None
    related_capa_id: Optional[str] = None
    related_inspection_id: Optional[str] = None
    reasons: List[str] = Field(default_factory=list, description="All specific blocking or attention conditions")
    citations: List[Citation] = Field(default_factory=list, description="Verified citations for record navigation")


