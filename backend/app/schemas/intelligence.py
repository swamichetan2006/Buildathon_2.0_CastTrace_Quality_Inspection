class MatchingAttribute(BaseModel):
    name: str = Field(..., description="Attribute name (e.g. SAME_PRODUCT, IDENTICAL_CATEGORY, SURFACE_LOCATION)")
    matched: bool = Field(..., description="Whether this attribute matched")
    weight: float = Field(..., description="Scoring weight assigned to this component")
