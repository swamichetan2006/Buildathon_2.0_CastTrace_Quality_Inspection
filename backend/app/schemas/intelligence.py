class HistoricalDefectMatch(BaseModel):
    defect_id: str = Field(..., description="Historical defect UUID")
    defect_number: str = Field(..., description="Business identifier DEF-YYYYMMDD-XXXX")
    category: str = Field(..., description="Defect category")
    severity: str = Field(..., description="Defect severity")
    status: str = Field(..., description="Actual defect lifecycle status (e.g. PENDING_REINSPECTION, OPEN, RESOLVED)")
    review_decision: Optional[str] = Field(None, description="Human review decision (e.g. CONFIRMED_DEFECTIVE, DISPUTED)")
    surface_location: Optional[str] = Field(None, description="Surface location on casting")
    description: Optional[str] = Field(None, description="Stored defect description")
    created_at: datetime = Field(..., description="Timestamp when defect was logged")

    # Associated batch & product
    batch_id: Optional[str] = None
    batch_number: Optional[str] = None
    product_id: Optional[str] = None
    product_sku: Optional[str] = None
    product_name: Optional[str] = None
    is_cross_product: bool = Field(False, description="True if from a different product/component")

    # Scoring & explainability
    match_score: float = Field(..., description="Relative ranking score between 0.0 and 100.0 (NOT a probability)")
    confidence_tier: str = Field(..., description="HIGH (>=75), MODERATE (>=45), LOW (<45)")
    matching_attributes: List[str] = Field(default_factory=list, description="List of matched attribute codes")
    matching_reasons: List[str] = Field(default_factory=list, description="Explainable matching factors")
    attribute_breakdown: List[MatchingAttribute] = Field(default_factory=list, description="Detailed component scores")

    # Prior recurrence links
    has_prior_link: bool = Field(False, description="Direct prior_defect_id lineage connection")

    # Historical actions & outcomes
    corrective_actions: List[Dict[str, Any]] = Field(default_factory=list, description="CAPAs taken on historical defect")
    reinspections: List[Dict[str, Any]] = Field(default_factory=list, description="Reinspection records and outcomes")
    resolution_notes: Optional[str] = None
    resolved_at: Optional[datetime] = None

    citations: List[Citation] = Field(default_factory=list, description="Navigation citations")


